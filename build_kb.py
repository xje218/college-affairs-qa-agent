def answer(q):
    q = q or ""
    b = BOUNDARY
    # 边界优先
    if any(k in q for k in b["medical"]):
        return {"type":"boundary","kind":"medical","conclusion":b["responses"]["medical"],"basis":[],"next":""}
    if any(k in q for k in b["investment"]):
        return {"type":"boundary","kind":"investment","conclusion":b["responses"]["investment"],"basis":[],"next":""}
    de = b["disciplinary_evade"]
    if any(k in q for k in de["must"]) and any(k in q for k in de["signal"]):
        return {"type":"boundary","kind":"disciplinary_evade","conclusion":b["responses"]["disciplinary_evade"],"basis":[],"next":""}
    pr = b["proxy"]
    if any(k in q for k in pr["signal"]):
        return {"type":"boundary","kind":"proxy","conclusion":b["responses"]["proxy"],"basis":[],"next":""}
    # 主题匹配
    best, best_score = None, 0
    for t in TOPICS:
        score = sum(1 for k in t["keywords"] if k in q)
        if score > best_score:
            best, best_score = t, score
    if best and best_score >= 1:
        return {"type":"topic","id":best["id"],"conclusion":best["conclusion"],"basis":best["basis"],"next":best["next"]}
    return {"type":"fallback","conclusion":FALLBACK,"basis":[],"next":""}

